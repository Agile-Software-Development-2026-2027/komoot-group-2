-- Initial MyWay schema (see DBScheme.mdd in the repository root).
-- Flyway applies this once; never edit it after it has been merged: add a V2__..., V3__... file instead.
--
-- Notes:
--  * "user" is a reserved word in PostgreSQL, so the table is called "users".
--  * ENUM columns are stored as VARCHAR and mapped to Java enums (@Enumerated(EnumType.STRING)),
--    so adding a new enum value does not require a migration.

CREATE TABLE users (
    email    VARCHAR(255) PRIMARY KEY,
    username VARCHAR(50)  NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL -- BCrypt hash, never the plain password
);

CREATE TABLE route (
    id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category                  VARCHAR(30)      NOT NULL,
    publisher                 VARCHAR(255)     NOT NULL REFERENCES users (email) ON UPDATE CASCADE,
    picture_path              VARCHAR(255),
    difficulty                VARCHAR(30)      NOT NULL,
    estimated_time_in_minutes INTEGER          CHECK (estimated_time_in_minutes >= 0),
    length_in_meters          DOUBLE PRECISION CHECK (length_in_meters >= 0),
    is_active                 BOOLEAN          NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_route_publisher ON route (publisher);

CREATE TABLE waypoint (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category    VARCHAR(30)      NOT NULL,
    description TEXT,
    publisher   VARCHAR(255)     NOT NULL REFERENCES users (email) ON UPDATE CASCADE,
    is_active   BOOLEAN          NOT NULL DEFAULT TRUE,
    latitude    DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude   DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_waypoint_publisher ON waypoint (publisher);

CREATE TABLE waypoint_pictures (
    waypoint_id  INTEGER      NOT NULL REFERENCES waypoint (id) ON DELETE CASCADE,
    picture_path VARCHAR(255) NOT NULL,
    PRIMARY KEY (waypoint_id, picture_path)
);

CREATE TABLE report_route (
    route_id       INTEGER      NOT NULL REFERENCES route (id) ON DELETE CASCADE,
    reporter_email VARCHAR(255) NOT NULL REFERENCES users (email) ON UPDATE CASCADE ON DELETE CASCADE,
    PRIMARY KEY (route_id, reporter_email)
);

CREATE TABLE report_waypoint (
    waypoint_id    INTEGER      NOT NULL REFERENCES waypoint (id) ON DELETE CASCADE,
    reporter_email VARCHAR(255) NOT NULL REFERENCES users (email) ON UPDATE CASCADE ON DELETE CASCADE,
    PRIMARY KEY (waypoint_id, reporter_email)
);
